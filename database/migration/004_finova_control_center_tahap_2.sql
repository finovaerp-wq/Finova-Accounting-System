-- Security definer helper supaya policy tidak recursive.
create or replace function public.is_finova_super_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.finova_super_admins a
        where a.user_uid = (select auth.uid())
          and a.is_active = true
    );
$$;

revoke all on function public.is_finova_super_admin() from public;
grant execute on function public.is_finova_super_admin() to authenticated;

-- Tenant context yang nanti dipakai pada Tahap RLS transaksi.
create or replace function public.finova_current_company_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
    select cu.company_id
    from public.finova_company_users cu
    where cu.user_uid = (select auth.uid())
      and cu.status = 'ACTIVE'
    order by cu.created_at desc
    limit 1;
$$;

revoke all on function public.finova_current_company_id() from public;
grant execute on function public.finova_current_company_id() to authenticated;

-- Super Admin dapat menghubungkan user Auth yang sudah ada ke company berdasarkan email.
create or replace function public.finova_admin_assign_user(
    p_email text,
    p_company_id uuid,
    p_role text default 'STAFF'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_uid uuid;
    v_role text;
begin
    if not public.is_finova_super_admin() then
        raise exception 'Access denied: FINOVA Super Admin required.';
    end if;

    v_role := upper(coalesce(p_role, 'STAFF'));
    if v_role not in ('MANAGER','STAFF','VIEWER') then
        raise exception 'Invalid company role.';
    end if;

    select id into v_user_uid
    from auth.users
    where lower(email) = lower(trim(p_email))
    limit 1;

    if v_user_uid is null then
        raise exception 'Auth user with email % was not found.', p_email;
    end if;

    insert into public.finova_company_users(company_id, user_uid, role, status)
    values(p_company_id, v_user_uid, v_role, 'ACTIVE')
    on conflict(company_id, user_uid)
    do update set role = excluded.role, status = 'ACTIVE', updated_at = now();

    update public.mst_users
       set company_id = p_company_id
     where user_uid = v_user_uid;

    return v_user_uid;
end;
$$;

revoke all on function public.finova_admin_assign_user(text,uuid,text) from public;
grant execute on function public.finova_admin_assign_user(text,uuid,text) to authenticated;

-- List user untuk Control Center; auth.users tidak diekspos langsung ke browser.
create or replace function public.finova_admin_list_users()
returns table(
    user_uid uuid,
    email text,
    full_name text,
    company_id uuid,
    company_name text,
    company_role text,
    membership_status text
)
language sql
stable
security definer
set search_path = ''
as $$
    select
        au.id,
        au.email::text,
        coalesce(mu.full_name, au.raw_user_meta_data ->> 'full_name', '')::text,
        cu.company_id,
        c.company_name::text,
        cu.role::text,
        cu.status::text
    from auth.users au
    left join public.mst_users mu on mu.user_uid = au.id
    left join public.finova_company_users cu on cu.user_uid = au.id and cu.status = 'ACTIVE'
    left join public.finova_companies c on c.id = cu.company_id
    where public.is_finova_super_admin()
    order by lower(coalesce(au.email,''));
$$;

revoke all on function public.finova_admin_list_users() from public;
grant execute on function public.finova_admin_list_users() to authenticated;

