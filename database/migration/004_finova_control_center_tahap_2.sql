create extension if not exists pgcrypto;

create table if not exists public.finova_companies (
    id uuid primary key default gen_random_uuid(),
    company_code text not null unique,
    company_name text not null,
    legal_name text,
    email text,
    phone text,
    address text,
    max_users integer not null default 5 check (max_users > 0),
    status text not null default 'ACTIVE' check (status in ('ACTIVE','SUSPENDED','INACTIVE')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.finova_super_admins (
    id bigint generated by default as identity primary key,
    user_uid uuid not null unique references auth.users(id) on delete cascade,
    full_name text,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.finova_plans (
    id uuid primary key default gen_random_uuid(),
    plan_code text not null unique,
    plan_name text not null,
    billing_cycle text not null check (billing_cycle in ('MONTHLY','ANNUAL')),
    price numeric(18,2) not null default 0,
    max_users integer not null default 5,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.finova_subscriptions (
    id uuid primary key default gen_random_uuid(),
    company_id uuid not null references public.finova_companies(id) on delete cascade,
    plan_id uuid not null references public.finova_plans(id),
    start_date date not null,
    end_date date not null,
    amount numeric(18,2) not null default 0,
    payment_status text not null default 'UNPAID' check (payment_status in ('PAID','UNPAID','OVERDUE','CANCELLED')),
    status text not null default 'ACTIVE' check (status in ('ACTIVE','EXPIRED','CANCELLED')),
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (end_date >= start_date)
);

create table if not exists public.finova_company_users (
    id uuid primary key default gen_random_uuid(),
    company_id uuid not null references public.finova_companies(id) on delete cascade,
    user_uid uuid not null references auth.users(id) on delete cascade,
    role text not null default 'STAFF' check (role in ('MANAGER','STAFF','VIEWER')),
    status text not null default 'ACTIVE' check (status in ('ACTIVE','INACTIVE')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(company_id, user_uid)
);

